export function isLang(v: unknown): v is Lang {
  return v === 'nl' || v === 'en';
}

/** Taal van een bewaarde waarde of van een verzoek: alles wat geen 'en' is blijft Nederlands (oude avonturen). */
export function langOf(v: unknown): Lang {
  return v === 'en' ? 'en' : 'nl';
}

/** Voor datums en getallen (Intl). */
export function localeOf(lang: Lang): string {
  return lang === 'en' ? 'en-GB' : 'nl-NL';
}


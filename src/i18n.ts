export function setCurrentLang(lang: Lang): void {
  current = lang;
}
export function currentLang(): Lang {
  return current;
}
/** t() in de huidige taal van de app, voor code buiten React. */
export function tt(key: Key, vars?: Vars): string {
  return t(current, key, vars);
}


const DICT: Record<Lang, Record<Key, string>> = { nl, en };

export type Vars = Record<string, string | number>;

/** Zoekt de tekst bij een sleutel en vult {plaatsvervangers} in. Onbekende plaatsvervangers blijven staan. */
export function t(lang: Lang, key: Key, vars?: Vars): string {
  const text = DICT[lang][key] ?? DICT.nl[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
}

/** Sleutels met een enkelvoud (`.one`) en meervoud (`.other`): `tn('end.left', 3)` kiest end.left.other met {n} = 3. */
export type PluralBase<K extends string = Key> = K extends `${infer B}.one` ? B : never;

export function tn(lang: Lang, base: PluralBase, n: number, vars?: Vars): string {
  return t(lang, `${base}.${n === 1 ? 'one' : 'other'}` as Key, { n, ...vars });
}

